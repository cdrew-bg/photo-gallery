function readScripts() {
  const pkg = JSON.parse(readFileSync(PACKAGE_JSON, 'utf8'));
  return pkg.scripts ?? {};
}

function validate(scripts) {
  const missing = SPEC.filter((tool) => !(tool.script in scripts)).map((tool) => tool.script);
  if (missing.length === 0) return;
  process.stderr.write(`gen-dev-skill: spec references missing package.json scripts:\n`);
  for (const name of missing) process.stderr.write(`  ${name}\n`);
  process.exit(1);
}

function buildManifest() {
  const tools = SPEC.map((tool) => ({
    name: tool.name,
    script: tool.script,
    description: tool.desc,
    mutates: tool.mutates,
  }));
  return `${JSON.stringify({ server: 'dev', tools }, undefined, JSON_INDENT)}\n`;
}

function renderRow(tool) {
  const effect = tool.mutates ? 'writes' : 'read-only';
  return `| \`mcp__dev__${tool.name}\` | \`pnpm ${tool.script}\` | ${effect} | ${tool.desc} |`;
}

function renderRulesTable() {
  const rules = JSON.parse(readFileSync(RULES_JSON, 'utf8'));
  const rows = Object.entries(rules)
    .map(([name, why]) => `| \`local/${name}\` | ${why} |`)
    .join('\n');
  return `| Rule | WHY |\n| --- | --- |\n${rows}`;
}

