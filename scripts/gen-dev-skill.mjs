function writeFile(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function checkDrift(path, content) {
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    current = '';
  }
  return current === content ? undefined : path;
}

function runCheck(manifest, skill) {
  const drifted = [checkDrift(MANIFEST_PATH, manifest), checkDrift(SKILL_PATH, skill)].filter(
    Boolean,
  );
  if (drifted.length === 0) {
    process.stdout.write('gen-dev-skill: dev skill and manifest are in sync\n');
    return;
  }
  process.stderr.write('gen-dev-skill: out of sync — run `node scripts/gen-dev-skill.mjs`:\n');
  for (const path of drifted) process.stderr.write(`  ${path}\n`);
  process.exit(1);
}

function main() {
  validate(readScripts());
  const manifest = buildManifest();
  const skill = renderSkill();
  if (process.argv.includes(CHECK_FLAG)) {
    runCheck(manifest, skill);
    return;
  }
  writeFile(MANIFEST_PATH, manifest);
  writeFile(SKILL_PATH, skill);
  process.stdout.write(`gen-dev-skill: wrote ${MANIFEST_PATH} and ${SKILL_PATH}\n`);
}

main();
